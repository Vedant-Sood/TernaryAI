"""Model card generator. Results are read from results/*.json, never typed in by hand."""

from __future__ import annotations

import json
import os

SPEC = {
    "tricode": dict(title="TriCode", domain="programming and software engineering",
                    tasks="Python and other languages, algorithms, debugging, explanation, refactoring, unit tests",
                    datasets=["bigcode/self-oss-instruct-sc2-exec-filter-50k", "nvidia/OpenCodeInstruct"],
                    licences="ODC-By, CC-BY-4.0", benches="HumanEval, MBPP (test), synthetic code tasks"),
    "trimath": dict(title="TriMath", domain="mathematics and symbolic reasoning",
                    tasks="algebra, calculus, number theory, probability, multi-step word problems, proofs",
                    datasets=["AI-MO/NuminaMath-CoT", "nvidia/OpenMathInstruct-2", "openai/gsm8k"],
                    licences="Apache-2.0, CC-BY-4.0, MIT", benches="GSM8K, MATH-500, synthetic maths"),
    "trireason": dict(title="TriReason", domain="scientific and technical reasoning",
                      tasks="physics, engineering, quantitative analysis, formal logic, technical explanation",
                      datasets=["TIGER-Lab/WebInstructSub", "allenai/ai2_arc"],
                      licences="Apache-2.0, CC-BY-SA-4.0", benches="ARC-Challenge, synthetic science and logic"),
}


def _results_table(paths):
    rows = []
    for p in paths:
        if not os.path.exists(p):
            continue
        s = json.load(open(p))
        for bench, r in s.get("results", {}).items():
            if "error" in r:
                rows.append(f"| {s['model']} | {bench} | not executed | - | {r['error'][:60]} |")
                continue
            if bench == "val_loss":
                rows.append(f"| {s['model']} | val loss / ppl | {r['val_loss']:.4f} / {r['val_ppl']:.2f} | "
                            f"{r['n_batches']} batches | {s['status']} |")
            elif bench == "synthetic":
                em = r["exact_match"]
                rows.append(f"| {s['model']} | synthetic exact match | {em['accuracy']:.1%} | {em['n']} | {s['status']} |")
                if "code_pass@1" in r:
                    c = r["code_pass@1"]
                    rows.append(f"| {s['model']} | synthetic code pass@1 | {c['accuracy']:.1%} | {c['n']} | {s['status']} |")
            else:
                rows.append(f"| {s['model']} | {bench} ({r.get('metric', '')}) | {r['accuracy']:.1%} | {r['n']} | "
                            f"{s['status']} |")
    if not rows:
        return "_No evaluation results yet._\n"
    return "| Model | Benchmark | Score | n | Status |\n| --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n"


def render(specialist: str, status_2b: str, result_paths=(), extra_notes: str = "") -> str:
    s = SPEC[specialist]
    meta = ["---", "license: mit", "language: [en]", "library_name: triforge", "pipeline_tag: text-generation",
            "base_model: microsoft/bitnet-b1.58-2B-4T-bf16",
            "tags: [ternary, bitnet, 1.58-bit, quantization-aware-training, " + specialist + "]",
            "datasets:"] + [f"- {d}" for d in s["datasets"]] + ["---", ""]
    body = f"""# {s['title']}: ternary-weight specialist for {s['domain']}

Part of **TriForge** (TriCode, TriMath, TriReason): language models whose transformer weights are
ternary, W ∈ {{-1, 0, +1}} with one scale per matrix, and whose matmul inputs are 8-bit (W1.58A8, as in
BitNet b1.58).

## Status

{status_2b}

## Model

* Base: [microsoft/bitnet-b1.58-2B-4T-bf16](https://huggingface.co/microsoft/bitnet-b1.58-2B-4T-bf16)
  (MIT), a natively ternary 2.41B-parameter model pre-trained on 4T tokens.
* Method: quantization-aware supervised fine-tuning. The forward weights are ternary at every training step
  (absmean + straight-through estimator). On an 8 GB GPU only the last 8 of 30 blocks keep bf16
  latent weights; the other blocks stay frozen as packed 2-bit codes.
* Parameters: 2,412,820,480 in total. 2,084,044,800 (86.4%) are ternary. The 328M-parameter tied
  token embedding / LM head and the RMSNorm gains are bf16.
* Intended scope: {s['tasks']}.
* Storage: 2-bit packed codes + bf16 embedding ≈ 1.1 GB of weights (estimate; the 1.58-bit bound is
  lower, and this format does not reach it).
* Speed: the PyTorch reference path is **not** faster than a dense model. Ternary speedups need
  specialised kernels such as bitnet.cpp, and none are claimed here.

## Training data

{', '.join(s['datasets'])} ({s['licences']}), plus verified synthetic problems generated by TriForge.
Exact and near-duplicate removal, and 13-gram decontamination against the evaluation benchmarks. See
`docs/DATA.md` and the dataset `manifest.json` shipped with the training run for counts and versions.

## Evaluation

Benchmarks: {s['benches']}, with greedy decoding. Every number below was measured by
`scripts/evaluate.py`; `n` is the number of examples evaluated.

{_results_table(result_paths)}
{extra_notes}
## Limitations

* Small model, English-centred, and it can be confidently wrong. Check generated code and maths before using them.
* Benchmark prompts approximate the official harnesses. Numbers are comparable within TriForge, not
  necessarily with leaderboards.
* The base model card says BitNet 2B4T is for research and is not recommended for commercial
  deployment without further testing. That applies here too.
* Licence terms of the training data (CC-BY attribution, synthetic-data provenance) are listed in `docs/DATA.md`.

## Usage

```bash
pip install -e .   # from the TriForge repository
python scripts/download_hf.py --repo <owner>/{s['title']}-2B-ternary --out checkpoints/exports/{specialist}-2b
triforge chat -m {specialist}
```
"""
    return "\n".join(meta) + body
